// release-notes: a draft of the GitHub release notes for a tag (the release workflow publishes it
// as a draft; edit before publishing).
//
//   omnivar-testkit release-notes --tag v0.2.0 [--previous v0.1.0] [--checksums SHA256SUMS]
//       [--bench bench.txt] [--build "text"] [--repo owner/name] [--highlights notes.md]
//
// Changes: the commit subjects from the previous tag (default: the closest tag before --tag, or
// the whole history) to --tag, grouped by their first word. Downloads: the lines of
// `sha256sum` output. Verification: the aardvark table, recall and snapshot lines of a `bench` run.
// Highlights: hand-written Markdown (the release workflow passes docs/release-notes/<tag>.md when
// it exists), printed after the introduction. Without a previous tag the notes describe the first
// release and list no commits.

#include <map>
#include <print>

#include "testkit.hpp"

namespace testkit {

namespace {

std::string git(const std::vector<std::string>& args, bool required = true) {
    std::vector<std::string> cmd = {"git", "-C", root().string()};
    cmd.insert(cmd.end(), args.begin(), args.end());
    const auto r = run(cmd);
    if (r.rc != 0 && required) die("git " + join(args, " ") + " failed: " + last_line(r.err));
    return r.rc == 0 ? std::string(strip(r.out)) : std::string();
}

// The group a commit subject goes to.
std::string group_of(std::string_view subject) {
    auto starts = [&](std::string_view p) {
        return subject.size() >= p.size() && std::equal(p.begin(), p.end(), subject.begin(), [](char a, char b) {
                   return std::tolower(static_cast<unsigned char>(a)) == std::tolower(static_cast<unsigned char>(b));
               });
    };
    if (starts("docs") || starts("readme")) return "Documentation";
    if (starts("ci") || starts("test") || starts("lint") || starts("release") || starts("build"))
        return "Build, tests and CI";
    if (starts("fix") || subject.contains(" fix") || starts("bug")) return "Fixes";
    return "Changes";
}

}  // namespace

int cmd_release_notes(Args& args) {
    const auto tag = args.required("--tag");
    auto previous = args.value("--previous");
    const auto checksums = args.value("--checksums");
    const auto bench = args.value("--bench");
    const auto build = args.value("--build");
    const auto repo = args.value("--repo");
    const auto highlights = args.value("--highlights");
    args.finish();

    if (!previous) {
        const auto p = git({"describe", "--tags", "--abbrev=0", tag + "^"}, false);
        if (!p.empty()) previous = p;
    }
    const std::string range = previous ? *previous + ".." + tag : tag;
    const auto log = git({"log", "--no-merges", "--format=%h%x09%s", range});
    std::map<std::string, std::vector<std::string>> groups;
    std::size_t n = 0;
    for (const auto& l : lines(log)) {
        const auto tab = l.find('\t');
        if (tab == std::string::npos) continue;
        const auto sha = l.substr(0, tab), subject = l.substr(tab + 1);
        groups[group_of(subject)].push_back(std::format("- {} ({})", subject, sha));
        ++n;
    }

    std::string version = tag;
    if (version.starts_with('v')) version.erase(0, 1);
    std::println("# omnivar {}", version);
    std::println("");
    if (previous)
        std::println("Draft generated by the release workflow from `{}...{}` ({} commit{}). Edit before publishing.",
                     *previous, tag, n, n == 1 ? "" : "s");
    else if (!highlights)  // a first release with highlights introduces itself
        std::println(
            "The first release of omnivar. (Draft generated by the release workflow; edit before publishing.)");
    if (previous || !highlights) std::println("");
    if (highlights) {
        std::print("{}", read_file(*highlights));
        std::println("");
    }
    std::println("## Downloads");
    std::println("");
    std::println(
        "`omnivar-{}-linux-x86_64.tar.gz`: a fully static x86-64 Linux binary (glibc, built on Debian trixie), with "
        "`LICENSE`, `THIRD_PARTY_LICENSES` and `README.md`. It needs no libraries on the target machine.",
        tag);
    if (build) std::println("Build: {}.", *build);
    if (checksums) {
        std::println("");
        std::println("| File | SHA-256 |");
        std::println("|---|---|");
        for (const auto& l : lines(read_file(*checksums))) {
            const auto w = words(l);
            if (w.size() == 2) std::println("| `{}` | `{}` |", w[1].starts_with('*') ? w[1].substr(1) : w[1], w[0]);
        }
        std::println("");
        std::println("Check with `sha256sum -c SHA256SUMS`.");
    }
    // First release: everything is new, so the commit list adds nothing to the highlights.
    if (previous) {
        std::println("");
        std::println("## What changed");
    }
    for (const char* g : {"Changes", "Fixes", "Documentation", "Build, tests and CI"}) {
        if (!previous) break;
        const auto it = groups.find(g);
        if (it == groups.end()) continue;
        std::println("");
        std::println("### {}", g);
        std::println("");
        for (const auto& c : it->second) std::println("{}", c);
    }
    if (repo && previous) {
        std::println("");
        std::println("Full list: https://github.com/{}/compare/{}...{}", *repo, *previous, tag);
    }
    if (bench) {
        std::println("");
        std::println("## Verification");
        std::println("");
        std::println(
            "The release binary passed the unit tests, the regression cases (single sample and tumour/normal), "
            "the thread and -p invariants, the sanitizer runs and the Oncospan truth-set benchmark:");
        std::println("");
        std::println("```");
        bool table = false;
        for (const auto& l : lines(read_file(*bench))) {
            if (l.starts_with("aardvark GT")) table = true;
            if (table || l.starts_with("omnivar:") || l.starts_with("recall") || l.starts_with("snapshot") ||
                l.starts_with("RESULT"))
                std::println("{}", l);
            if (table && l.starts_with("JointIndel")) table = false;
        }
        std::println("```");
        std::println("");
        std::println(
            "The truth set lists only the sample's known variants, so recall is the measure here. FP counts the PASS "
            "calls that are not in the truth set, not a false-positive rate.");
    }
    return 0;
}

}  // namespace testkit
